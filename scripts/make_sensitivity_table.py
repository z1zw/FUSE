"""Turn results/sensitivity.csv into the table the paper prints.

One row per swept parameter: the range it was swept over, what the FUSE to
ASIC latency ratio did across that range, and what the Groth16 ablation gain
did. The point of the table is the contrast between the last row and the
others, so the rows are ordered to end on it.

    python scripts/make_sensitivity_table.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'results' / 'sensitivity.csv'
OUT = ROOT / 'sosp' / 'tab_sensitivity.tex'

LABEL = {
    'compute':   ('Op latency', r'$0.5$--$2.0\times$'),
    'bandwidth': ('Interconnect bandwidth', r'$16$--$256$\,B/cycle'),
    'cache':     ('Fragment cache', r'$0.5$--$8$\,MB'),
    'reconfig':  ('Reconfiguration latency', r'$575$--$9{,}200$\,cycles'),
    'asic_adv':  ('ASIC datapath advantage', r'$1.00$--$1.32\times$'),
}
ORDER = ['compute', 'bandwidth', 'cache', 'reconfig', 'asic_adv']


def span(frame):
    if frame.empty:
        return '---', '---'
    lo, hi = frame.ratio.min(), frame.ratio.max()
    if abs(hi - lo) < 5e-4:
        return f'${lo:.3f}$', r'$1.00\times$'
    return f'${lo:.3f}$--${hi:.3f}$', f'${hi/lo:.2f}' + r'\times$'


def main() -> None:
    d = pd.read_csv(SRC, comment='#')
    llm = d[d.study == 'llm_vs_asic']
    zkp = d[d.study == 'groth16_ablation']
    rows = []
    for axis in ORDER:
        name, swept = LABEL[axis]
        lr, ls = span(llm[llm.axis == axis])
        zr, zs = span(zkp[zkp.axis == axis])
        rows.append(f'{name} & {swept} & {lr} & {ls} & {zr} & {zs} \\\\')

    hw = llm[llm.axis.isin(['compute', 'bandwidth', 'cache', 'reconfig'])]
    hw_span = hw.ratio.max() / hw.ratio.min()
    adv = llm[llm.axis == 'asic_adv'].groupby('value').ratio.mean()
    worst = max(abs(r / v - 1) for v, r in adv.items())

    body = '\n'.join(rows)
    tex = rf"""% Generated by scripts/make_sensitivity_table.py -- do not edit.
\begin{{table}}[t]
\centering
\caption{{\textbf{{Sensitivity of both reported ratios to the simulator's own
parameters.}} Each row sweeps one parameter over the range shown with the
others held at the evaluated configuration. \emph{{FUSE/ASIC}} is the
language-model latency ratio, averaged over the \llmModelCount{{}} models of
\S\ref{{sec:llm}} on the prefill trace, where lower is better.
\emph{{Groth16 gain}} is the speedup over the degraded build, where higher is
better. \emph{{Span}} is the ratio of the extremes.}}
\label{{tab:sensitivity}}
\small
\setlength{{\tabcolsep}}{{4pt}}
\begin{{tabular}}{{|l|l|l|r|l|r|}}
\hline
\textbf{{Parameter}} & \textbf{{Swept over}} & \textbf{{FUSE/ASIC}} &
\textbf{{Span}} & \textbf{{Groth16 gain}} & \textbf{{Span}} \\
\hline
{body}
\hline
\end{{tabular}}
\end{{table}}
"""
    OUT.write_text(tex, encoding='utf-8')
    print(f'wrote {OUT}')
    print(f'  hardware axes move FUSE/ASIC by {100*(hw_span-1):.1f}% in total')
    print(f'  ratio tracks the assumed advantage to within '
          f'{100*worst:.1f}%')
    for v, r in adv.items():
        print(f'    advantage {v:.2f} -> ratio {r:.3f}')


if __name__ == '__main__':
    main()
