from __future__ import annotations
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence
import hashlib
import json
import os
import shutil
import subprocess
import sys

@dataclass(frozen=True)
class OpenSourceTool:
    name: str
    git_url: str
    default_dirname: str
OPEN_SOURCE_TOOLS: dict[str, OpenSourceTool] = {'dramsim3': OpenSourceTool(name='dramsim3', git_url='https://github.com/umd-memsys/DRAMsim3.git', default_dirname='DRAMsim3'), 'cacti': OpenSourceTool(name='cacti', git_url='https://github.com/HewlettPackard/cacti.git', default_dirname='cacti'), 'openroad': OpenSourceTool(name='openroad', git_url='https://github.com/The-OpenROAD-Project/OpenROAD-flow-scripts.git', default_dirname='OpenROAD-flow-scripts')}

def project_root() -> Path:
    return Path(__file__).resolve().parents[2]

def tools_root(root: Path | None=None) -> Path:
    return (root or project_root()) / 'external'

def ensure_tools_dir(root: Path | None=None) -> Path:
    path = tools_root(root)
    path.mkdir(parents=True, exist_ok=True)
    return path

def resolve_tool_repo(tool: str, root: Path | None=None) -> Path:
    spec = OPEN_SOURCE_TOOLS[tool]
    return ensure_tools_dir(root) / spec.default_dirname

def clone_or_update_repo(tool: str, *, root: Path | None=None, update: bool=False) -> Path:
    repo_dir = resolve_tool_repo(tool, root=root)
    spec = OPEN_SOURCE_TOOLS[tool]
    if repo_dir.exists():
        if update:
            _run(['git', '-C', str(repo_dir), 'pull', '--ff-only'])
        return repo_dir
    _run(['git', 'clone', '--depth', '1', spec.git_url, str(repo_dir)])
    return repo_dir

def find_executable(candidates: Iterable[Path]) -> Path | None:
    for path in candidates:
        if path.exists():
            return path
    return None

def dramsim3_binary(repo_dir: Path) -> Path | None:
    return find_executable([repo_dir / 'build' / 'dramsim3main', repo_dir / 'build' / 'dramsim3main.exe'])

def cacti_binary(repo_dir: Path) -> Path | None:
    return find_executable([repo_dir / 'cacti', repo_dir / 'cacti.exe'])

def host_build_tools() -> dict[str, str | None]:
    return {'git': shutil.which('git'), 'cmake': shutil.which('cmake'), 'make': shutil.which('make'), 'g++': shutil.which('g++'), 'bash': shutil.which('bash'), 'docker': shutil.which('docker')}

def git_head(repo_dir: Path) -> str | None:
    try:
        result = subprocess.run(['git', '-C', str(repo_dir), 'rev-parse', 'HEAD'], check=True, text=True, capture_output=True, env=dict(os.environ))
        return result.stdout.strip()
    except Exception:
        return None

def write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2), encoding='utf-8')

def write_dramsim3_trace(path: Path, *, total_bytes: int, burst_bytes: int=64, read_ratio: float=0.75, stride_bytes: int=64, start_addr: int=536870912, issue_gap_cycles: int=32) -> int:
    total_bytes = max(int(total_bytes), burst_bytes)
    request_count = max(1, (total_bytes + burst_bytes - 1) // burst_bytes)
    read_cutoff = int(request_count * max(0.0, min(read_ratio, 1.0)))
    lines: list[str] = []
    for idx in range(request_count):
        address = start_addr + idx * stride_bytes
        op = 'READ' if idx < read_cutoff else 'WRITE'
        cycle = idx * issue_gap_cycles
        lines.append(f'0x{address:X} {op} {cycle}')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return request_count

