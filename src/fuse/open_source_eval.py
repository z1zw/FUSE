def build_dramsim3(repo_dir: Path) -> Path:
    binary = dramsim3_binary(repo_dir)
    if binary is not None:
        return binary
    if shutil.which('cmake') is None:
        raise RuntimeError('cmake is required to build DRAMSim3')
    build_dir = repo_dir / 'build'
    build_dir.mkdir(parents=True, exist_ok=True)
    _run(['cmake', '-S', str(repo_dir), '-B', str(build_dir)])
    _run(['cmake', '--build', str(build_dir), '--config', 'Release'])
    binary = dramsim3_binary(repo_dir)
    if binary is None:
        raise RuntimeError('DRAMSim3 build completed but dramsim3main was not found')
    return binary

def build_cacti(repo_dir: Path) -> Path:
    binary = cacti_binary(repo_dir)
    if binary is not None:
        return binary
    make_bin = shutil.which('make')
    if make_bin is None:
        raise RuntimeError('make is required to build CACTI')
    _run([make_bin], cwd=repo_dir)
    binary = cacti_binary(repo_dir)
    if binary is None:
        raise RuntimeError('CACTI build completed but the cacti binary was not found')
    return binary

def run_dramsim3(repo_dir: Path, *, config_path: Path, trace_path: Path, output_dir: Path, cycles: int) -> subprocess.CompletedProcess:
    binary = build_dramsim3(repo_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    cmd = [str(binary), str(config_path), '-c', str(int(cycles)), '-t', str(trace_path), '-o', str(output_dir)]
    return _run(cmd)

def run_cacti(repo_dir: Path, *, config_path: Path, output_path: Path) -> subprocess.CompletedProcess:
    binary = build_cacti(repo_dir)
    result = _run([str(binary), '-infile', str(config_path)], capture_output=True, cwd=repo_dir)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(result.stdout or '', encoding='utf-8')
    return result

def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()

def file_metadata(path: Path | None) -> dict[str, object] | None:
    if path is None:
        return None
    path = Path(path)
    if not path.exists():
        return None
    return {'path': str(path.resolve()), 'size_bytes': int(path.stat().st_size), 'sha256': sha256_file(path)}

def _run(cmd: Sequence[str], *, capture_output: bool=False, cwd: Path | None=None) -> subprocess.CompletedProcess:
    return subprocess.run(list(cmd), check=True, text=True, capture_output=capture_output, env=dict(os.environ), cwd=str(cwd) if cwd is not None else None)

def platform_summary() -> dict[str, str]:
    return {'platform': sys.platform, 'python': sys.version.split()[0]}
